from __future__ import annotations

from app.domain.response_composer import GREETING, OPERATOR_FOOTER


def escalation_ack() -> str:
    return (
        "Ваш вопрос передан оператору.\n\n"
        "По текущему вопросу дождитесь ответа оператора. Если оператор попросит дополнительные детали, "
        "пришлите их в этом же обращении: можно уточнить суть проблемы, кратко описать, что произошло "
        "и указать шаги, на которых возникла проблема; при необходимости приложите скриншоты или другие материалы.\n\n"
        "Если у вас появится другой, новый вопрос, пожалуйста, создайте отдельный чат или заявку — так его будет проще и быстрее обработать."
    )


def rephrase_prompt() -> str:
    return (
        "Пожалуйста, переформулируйте вопрос короче и точнее: опишите только основную проблему, "
        "что именно не получается или что вы хотите сделать. По возможности без лишнего контекста и длинного рассказа."
    )


def choice_prompt(labels: list[str]) -> str:
    from app.domain.response_composer import ResponseComposer
    return ResponseComposer.choice(labels)


def oos_response() -> str:
    return (
        "Похоже, этот вопрос не относится к тем темам, которые мы можем обработать в этом чате. "
        "Пожалуйста, напишите вопрос, связанный с обучением, школами, приложением Терра, "
        "наставничеством или доступом к сервисам.\n\n"
        "Если вопрос всё же связан с нашей системой, опишите ситуацию подробнее или напишите «оператор»."
    )


# ---------------------------------------------------------------------------
# High-risk escalation replies (collect minimum data, then human)
# ---------------------------------------------------------------------------

def high_risk_refund_reply() -> str:
    return (
        "Простите, что вопрос затянулся. Обучение в Terra бесплатное, поэтому нам нужно понять, "
        "за что именно была оплата: аренда пространства, донат/подписка или другой платёж.\n\n"
        "Пожалуйста, пришлите:\n"
        "— ФИО;\n"
        "— телефон и email, указанные при регистрации;\n"
        "— дату и сумму платежа;\n"
        "— получателя платежа;\n"
        "— скриншот/чек оплаты;\n"
        "— на какую школу или мероприятие вы не смогли попасть.\n\n"
        "После этого передадим обращение ответственным для проверки и решения вопроса по возврату."
    )


def high_risk_personal_data_reply() -> str:
    return (
        "Нам жаль, что вы столкнулись с такой ситуацией. Мы передадим жалобу ответственным "
        "и разберём обращение.\n\n"
        "По удалению персональных данных: пожалуйста, подтвердите, что вы хотите именно удалить "
        "ваши данные из базы Terra, и укажите данные, по которым можно найти профиль: "
        "ФИО, телефон и/или email.\n\n"
        "После подтверждения запрос будет передан ответственному специалисту. "
        "Обратите внимание: часть данных может храниться в сроки и объёме, которые требуются "
        "по закону и правилам обработки обращений."
    )


def high_risk_complaint_reply() -> str:
    return (
        "Нам жаль, что вы столкнулись с такой ситуацией. Мы передадим обращение ответственным "
        "и разберём его.\n\n"
        "Пожалуйста, кратко опишите:\n"
        "— что произошло;\n"
        "— когда и в каком контексте (чат, мероприятие, школа);\n"
        "— ФИО или контакт, если хотите, чтобы мы могли найти ваше обращение.\n\n"
        "После этого команда свяжется с вами."
    )


def high_risk_reply(kind: str) -> str:
    """Return the structured collection reply for a high-risk category."""
    kind = (kind or "").lower().strip()
    if kind in {"refund", "high_risk:refund"}:
        return high_risk_refund_reply()
    if kind in {"personal_data", "pdn", "high_risk:personal_data", "high_risk:pdn"}:
        return high_risk_personal_data_reply()
    if kind in {"complaint", "high_risk:complaint"}:
        return high_risk_complaint_reply()
    return escalation_ack()
